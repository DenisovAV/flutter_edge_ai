// The EmbeddingGemma 2 text golden (R5 §10.1), in the form a device can read.
//
// integration_test/goldens/eg2_text_golden.json is the measurement run's
// eg2_text_golden_final.json with one of its six query/document pairs taken
// out on 2026-10-14 (the rest renumbered, and the `measured_spread` minima
// recomputed from the remaining items' own cosines): 10 strings (5 pairs),
// each with `vector` from the shipped native-v0.18.0-d macOS arm64
// libLiteRtLm.dylib (CPU), `vector_python_wheel` and `vector_st_fp32`
// (Sentence Transformers, fp32). A JSON file next to a test is not readable
// on a phone, so integration_test/goldens/eg2_text_golden.dart carries what
// embeddinggemma2_test.dart needs — the strings, their prefixes, `vector` and
// `vector_st_fp32` as base64 little-endian float32 (every value in the JSON is
// a float32, so nothing is rounded) — generated from the JSON by this test.
//
// Every run checks the Dart file against the JSON. To regenerate (never on CI):
//   cd packages/flutter_edge_ai/example
//   UPDATE_GOLDENS=1 flutter test test/eg2_text_golden_test.dart

import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:crypto/crypto.dart';
import 'package:flutter_test/flutter_test.dart';

import '../integration_test/goldens/eg2_text_golden.dart';
import '../integration_test/goldens/litertlm_llm_header.dart';

const _jsonPath = 'integration_test/goldens/eg2_text_golden.json';
const _dartPath = 'integration_test/goldens/eg2_text_golden.dart';

String _f32(List<dynamic> values) {
  final floats = Float32List(values.length);
  for (var i = 0; i < values.length; i++) {
    final v = (values[i] as num).toDouble();
    floats[i] = v;
    if (floats[i] != v) {
      throw StateError('value $i ($v) is not a float32; base64 would round it');
    }
  }
  final bytes = ByteData(values.length * 4);
  for (var i = 0; i < floats.length; i++) {
    bytes.setFloat32(i * 4, floats[i], Endian.little);
  }
  return base64.encode(bytes.buffer.asUint8List());
}

String _generate(Map<String, dynamic> source) {
  final payload = {
    'description':
        'Generated from eg2_text_golden.json by test/eg2_text_golden_test.dart. '
        'vector: native-v0.18.0-d macOS arm64 libLiteRtLm.dylib (CPU); '
        'vector_st_fp32: Sentence Transformers fp32. Both base64 '
        'little-endian float32.',
    'model': source['model'],
    'native_library': source['native_library'],
    'prefixes': source['prefixes'],
    'measured_spread': source['measured_spread'],
    'suggested_tolerances': source['suggested_tolerances'],
    'items': [
      for (final item in (source['items'] as List).cast<Map<String, dynamic>>())
        {
          'id': item['id'],
          'role': item['role'],
          'prefix': item['prefix'],
          'text': item['text'],
          'st_token_count_incl_bos_eos': item['st_token_count_incl_bos_eos'],
          'vector_f32le': _f32(item['vector'] as List),
          'vector_st_fp32_f32le': _f32(item['vector_st_fp32'] as List),
        },
    ],
  };
  final json = const JsonEncoder.withIndent('  ').convert(payload);
  if (json.contains("'''")) throw StateError('cannot embed in a raw string');
  return '''
// GENERATED by test/eg2_text_golden_test.dart from eg2_text_golden.json — do
// not edit. Regenerate: UPDATE_GOLDENS=1 flutter test test/eg2_text_golden_test.dart
//
// EmbeddingGemma 2 text golden (R5 §10.1) for integration_test/
// embeddinggemma2_test.dart. Vectors are base64 little-endian float32.
library;

const eg2TextGoldenJson = r\'\'\'
$json
\'\'\';
''';
}

void main() {
  test('the Dart golden is generated from the JSON golden', () {
    final source =
        jsonDecode(File(_jsonPath).readAsStringSync()) as Map<String, dynamic>;
    final expected = _generate(source);
    final file = File(_dartPath);
    if (Platform.environment['UPDATE_GOLDENS'] == '1') {
      if (Platform.environment.containsKey('CI')) {
        fail('UPDATE_GOLDENS is refused on CI');
      }
      file.writeAsStringSync(expected);
    }
    expect(
      file.existsSync() ? file.readAsStringSync() : '<missing>',
      expected,
      reason: '$_dartPath is stale: UPDATE_GOLDENS=1 flutter test $_dartPath',
    );
  });

  test('decoding the Dart golden gives exactly the JSON vectors', () {
    final source =
        jsonDecode(File(_jsonPath).readAsStringSync()) as Map<String, dynamic>;
    final golden = jsonDecode(eg2TextGoldenJson) as Map<String, dynamic>;
    final want = (source['items'] as List).cast<Map<String, dynamic>>();
    final got = (golden['items'] as List).cast<Map<String, dynamic>>();
    expect(got, hasLength(10));
    for (var i = 0; i < want.length; i++) {
      for (final (key, encoded) in [
        ('vector', 'vector_f32le'),
        ('vector_st_fp32', 'vector_st_fp32_f32le'),
      ]) {
        final bytes = ByteData.sublistView(
          base64.decode(got[i][encoded] as String),
        );
        final values = [
          for (var j = 0; j < bytes.lengthInBytes ~/ 4; j++)
            bytes.getFloat32(j * 4, Endian.little),
        ];
        expect(
          values,
          (want[i][key] as List).cast<num>().map((v) => v.toDouble()).toList(),
          reason: '${want[i]['id']} $key',
        );
      }
      expect(got[i]['text'], want[i]['text']);
      expect(got[i]['prefix'], want[i]['prefix']);
    }
  });

  test('the LLM header fixture is litertlm\'s, byte for byte', () {
    final fixture = File(
      '../../flutter_edge_ai_litertlm/test/ffi/fixtures/'
      'gemma3_1b_prefix.litertlm',
    ).readAsBytesSync();
    final embedded = base64.decode(
      litertlmLlmHeaderBase64.replaceAll(RegExp(r'\s'), ''),
    );
    expect(embedded, fixture);
    expect(sha256.convert(embedded).toString(), litertlmLlmHeaderSha256);
  });
}
