// LiteRT C API probe: the calls LiteRtBindings makes for a `.tflite`
// embedder (lib/src/embedding/litert_embedding_pass.dart), in the same order,
// against a built library. Compiled against the LiteRT headers of the pin, and
// every function pointer is typed from its declaration there, so a signature
// that moved fails the build, not the run.
//
//   cc -O1 -Wall -I<litert checkout> -I<dir with build_config.h> \
//      -o litert_probe litert_probe.c -ldl -lm
//   cl /std:clatest /I<litert checkout> /I<...> litert_probe.c   (Windows)
//   litert_probe <lib> <model.tflite> <cpu|gpu> [<out.f32>]
//
// litert/build_common/build_config.h is generated by Bazel and, at the pin,
// holds only its include guard: an empty file of that name will do.
//
// <lib> is the library that exports the LiteRT C API: libLiteRtLm on Apple
// and Android, libLiteRt on Linux and Windows. Two fixed id sequences are
// embedded twice each (no tokenizer here): the vectors must have the graph's
// dimension, be finite and non-zero, repeat bit for bit, and differ between
// the two inputs. <out.f32> receives both vectors, to compare one library
// with another.
#include <math.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "litert/c/litert_common.h"
#include "litert/c/litert_compiled_model.h"
#include "litert/c/litert_environment.h"
#include "litert/c/litert_model.h"
#include "litert/c/litert_options.h"
#include "litert/c/litert_tensor_buffer.h"

#if defined(_WIN32)
#include <malloc.h>
#include <windows.h>
typedef HMODULE LibHandle;
static LibHandle OpenLib(const char* path) { return LoadLibraryA(path); }
static void* Sym(LibHandle h, const char* name) {
  return (void*)GetProcAddress(h, name);
}
static void* AlignedAlloc(size_t size) { return _aligned_malloc(size, 64); }
static void AlignedFree(void* p) { _aligned_free(p); }
#define TYPEOF typeof
#else
#include <dlfcn.h>
typedef void* LibHandle;
static LibHandle OpenLib(const char* path) {
  return dlopen(path, RTLD_NOW | RTLD_LOCAL);
}
static void* Sym(LibHandle h, const char* name) { return dlsym(h, name); }
static void* AlignedAlloc(size_t size) {
  return aligned_alloc(64, (size + 63) / 64 * 64);
}
static void AlignedFree(void* p) { free(p); }
#define TYPEOF __typeof__
#endif

#define FN(name) static TYPEOF(&name) p_##name
FN(LiteRtCreateEnvironment);
FN(LiteRtDestroyEnvironment);
FN(LiteRtCreateModelFromFile);
FN(LiteRtDestroyModel);
FN(LiteRtGetModelSignature);
FN(LiteRtGetNumSignatureInputs);
FN(LiteRtGetSignatureInputName);
FN(LiteRtCreateOptions);
FN(LiteRtDestroyOptions);
FN(LiteRtSetOptionsHardwareAccelerators);
FN(LiteRtCreateCompiledModel);
FN(LiteRtDestroyCompiledModel);
FN(LiteRtGetCompiledModelInputTensorLayout);
FN(LiteRtGetCompiledModelOutputTensorLayouts);
FN(LiteRtCreateTensorBufferFromHostMemory);
FN(LiteRtDestroyTensorBuffer);
FN(LiteRtRunCompiledModel);
FN(LiteRtLockTensorBuffer);
FN(LiteRtUnlockTensorBuffer);

static int g_missing = 0;
static void* Load(LibHandle lib, const char* name) {
  void* f = Sym(lib, name);
  if (!f) {
    fprintf(stderr, "missing export %s\n", name);
    g_missing++;
  }
  return f;
}
#define LOAD(name) p_##name = (TYPEOF(p_##name))Load(lib, #name)

#define CHECK(call)                                                   \
  do {                                                                \
    LiteRtStatus s_ = (call);                                         \
    if (s_ != kLiteRtStatusOk) {                                      \
      printf("RESULT litert FAIL %s status=%d\n", #call, (int)s_);    \
      exit(1);                                                        \
    }                                                                 \
  } while (0)

static LiteRtCompiledModel g_compiled;
static int g_seq, g_dim;

static float* Embed(const int* ids, int n) {
  LiteRtRankedTensorType in_type = {0};
  in_type.element_type = kLiteRtElementTypeInt32;
  in_type.layout.rank = 2;
  in_type.layout.dimensions[0] = 1;
  in_type.layout.dimensions[1] = g_seq;
  LiteRtRankedTensorType out_type = in_type;
  out_type.element_type = kLiteRtElementTypeFloat32;
  out_type.layout.dimensions[1] = g_dim;
  int32_t* in_host = AlignedAlloc((size_t)g_seq * 4);
  float* out_host = AlignedAlloc((size_t)g_dim * 4);
  for (int i = 0; i < g_seq; i++) in_host[i] = i < n ? ids[i] : 0;
  LiteRtTensorBuffer in_buf = NULL, out_buf = NULL;
  CHECK(p_LiteRtCreateTensorBufferFromHostMemory(&in_type, in_host,
                                                 (size_t)g_seq * 4, NULL,
                                                 &in_buf));
  CHECK(p_LiteRtCreateTensorBufferFromHostMemory(&out_type, out_host,
                                                 (size_t)g_dim * 4, NULL,
                                                 &out_buf));
  CHECK(p_LiteRtRunCompiledModel(g_compiled, 0, 1, &in_buf, 1, &out_buf));
  void* locked = NULL;
  CHECK(p_LiteRtLockTensorBuffer(out_buf, &locked,
                                 kLiteRtTensorBufferLockModeRead));
  float* v = malloc((size_t)g_dim * sizeof(float));
  memcpy(v, locked, (size_t)g_dim * sizeof(float));
  p_LiteRtUnlockTensorBuffer(out_buf);
  p_LiteRtDestroyTensorBuffer(in_buf);
  p_LiteRtDestroyTensorBuffer(out_buf);
  AlignedFree(in_host);
  AlignedFree(out_host);
  return v;
}

static double Norm(const float* v) {
  double s = 0;
  for (int i = 0; i < g_dim; i++) s += (double)v[i] * v[i];
  return sqrt(s);
}
static double Cos(const float* a, const float* b) {
  double d = 0;
  for (int i = 0; i < g_dim; i++) d += (double)a[i] * b[i];
  return d / (Norm(a) * Norm(b));
}
static bool Finite(const float* v) {
  for (int i = 0; i < g_dim; i++)
    if (!isfinite(v[i])) return false;
  return true;
}

int main(int argc, char** argv) {
  if (argc < 4) {
    fprintf(stderr, "usage: %s <lib> <model.tflite> <cpu|gpu> [<out.f32>]\n",
            argv[0]);
    return 64;
  }
  LibHandle lib = OpenLib(argv[1]);
  if (!lib) {
    fprintf(stderr, "cannot load %s\n", argv[1]);
    return 3;
  }
  LOAD(LiteRtCreateEnvironment);
  LOAD(LiteRtDestroyEnvironment);
  LOAD(LiteRtCreateModelFromFile);
  LOAD(LiteRtDestroyModel);
  LOAD(LiteRtGetModelSignature);
  LOAD(LiteRtGetNumSignatureInputs);
  LOAD(LiteRtGetSignatureInputName);
  LOAD(LiteRtCreateOptions);
  LOAD(LiteRtDestroyOptions);
  LOAD(LiteRtSetOptionsHardwareAccelerators);
  LOAD(LiteRtCreateCompiledModel);
  LOAD(LiteRtDestroyCompiledModel);
  LOAD(LiteRtGetCompiledModelInputTensorLayout);
  LOAD(LiteRtGetCompiledModelOutputTensorLayouts);
  LOAD(LiteRtCreateTensorBufferFromHostMemory);
  LOAD(LiteRtDestroyTensorBuffer);
  LOAD(LiteRtRunCompiledModel);
  LOAD(LiteRtLockTensorBuffer);
  LOAD(LiteRtUnlockTensorBuffer);
  printf("INFO litert missing_exports=%d\n", g_missing);
  if (g_missing) return 4;

  LiteRtEnvironment env = NULL;
  CHECK(p_LiteRtCreateEnvironment(0, NULL, &env));
  LiteRtModel model = NULL;
  CHECK(p_LiteRtCreateModelFromFile(env, argv[2], &model));
  LiteRtSignature sig = NULL;
  LiteRtParamIndex num_inputs = 0;
  CHECK(p_LiteRtGetModelSignature(model, 0, &sig));
  CHECK(p_LiteRtGetNumSignatureInputs(sig, &num_inputs));
  const char* in_name = NULL;
  CHECK(p_LiteRtGetSignatureInputName(sig, 0, &in_name));
  printf("INFO litert inputs=%zu first=%s\n", (size_t)num_inputs,
         in_name ? in_name : "?");
  LiteRtOptions options = NULL;
  CHECK(p_LiteRtCreateOptions(&options));
  bool gpu = !strcmp(argv[3], "gpu");
  CHECK(p_LiteRtSetOptionsHardwareAccelerators(
      options, gpu ? kLiteRtHwAcceleratorGpu : kLiteRtHwAcceleratorCpu));
  CHECK(p_LiteRtCreateCompiledModel(env, model, options, &g_compiled));
  LiteRtLayout in_layout, out_layout;
  memset(&in_layout, 0, sizeof in_layout);
  memset(&out_layout, 0, sizeof out_layout);
  CHECK(p_LiteRtGetCompiledModelInputTensorLayout(g_compiled, 0, 0,
                                                  &in_layout));
  CHECK(p_LiteRtGetCompiledModelOutputTensorLayouts(g_compiled, 0, 1,
                                                    &out_layout, false));
  g_seq = in_layout.dimensions[1];
  g_dim = out_layout.dimensions[1];
  printf("INFO litert seq=%d dim=%d backend=%s\n", g_seq, g_dim, argv[3]);

  // Fixed ids below every vocabulary size probed (Gecko, EmbeddingGemma).
  static const int a[] = {2, 651, 4320, 8426, 25341, 1163, 573, 27894, 5929, 1};
  static const int b[] = {2, 1841, 603, 573, 6037, 576, 6081, 1};
  int na = sizeof a / sizeof a[0], nb = sizeof b / sizeof b[0];
  float* va = Embed(a, na);
  float* va2 = Embed(a, na);
  float* vb = Embed(b, nb);
  int fail = 0;
  bool shape = g_dim > 0 && g_seq >= na;
  printf("RESULT litert_shape %s seq=%d dim=%d\n", shape ? "PASS" : "FAIL",
         g_seq, g_dim);
  fail += !shape;
  double norm = Norm(va);
  bool finite = Finite(va) && Finite(vb) && norm > 0;
  printf("RESULT litert_finite %s norm_a=%.6f norm_b=%.6f\n",
         finite ? "PASS" : "FAIL", norm, Norm(vb));
  fail += !finite;
  bool same = !memcmp(va, va2, (size_t)g_dim * sizeof(float));
  printf("RESULT litert_repeat %s\n", same ? "PASS" : "FAIL");
  fail += !same;
  double cab = Cos(va, vb);
  bool differ = cab < 0.9999;
  printf("RESULT litert_inputs_differ %s cos=%.6f\n", differ ? "PASS" : "FAIL",
         cab);
  fail += !differ;
  if (argc > 4) {
    FILE* f = fopen(argv[4], "wb");
    fwrite(va, sizeof(float), (size_t)g_dim, f);
    fwrite(vb, sizeof(float), (size_t)g_dim, f);
    fclose(f);
  }
  free(va);
  free(va2);
  free(vb);
  p_LiteRtDestroyCompiledModel(g_compiled);
  p_LiteRtDestroyOptions(options);
  p_LiteRtDestroyModel(model);
  p_LiteRtDestroyEnvironment(env);
  printf("RESULT litert %s %d check(s) failed\n", fail ? "FAIL" : "PASS", fail);
  return fail ? 1 : 0;
}
