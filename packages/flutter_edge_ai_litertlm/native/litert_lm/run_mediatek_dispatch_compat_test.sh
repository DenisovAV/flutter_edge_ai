#!/usr/bin/env bash
# Host test of the MediaTek dispatch adapter (mediatek_dispatch_compat.c):
# a fake legacy dispatch beside the adapter, queried the way LiteRT's
# versioned loader does, every slot called by name. Then the same test against
# an adapter that copies the basic table one slot off, which must fail — the
# check that the test can see the defect it exists for.
#
# LITERT_DIR=<LiteRT checkout at the pin> also builds the runner against the
# real litert/vendors/c/litert_dispatch_api.h, so the field names and order
# declared in the test are held to LiteRT's.
#
# POSIX (Linux, macOS); CI runs it on ubuntu.
set -euo pipefail
cd "$(dirname "$0")"

D="$(mktemp -d)"
trap 'rm -rf "$D"' EXIT
LIBS=()
[ "$(uname -s)" = Linux ] && LIBS=(-ldl -lpthread)
SO_FLAGS=(-shared -fPIC -fvisibility=hidden -Wall -Wextra -Werror)

build_case() {  # <dir> <adapter source> [fake defines...]
  local dir="$1" src="$2"
  shift 2
  mkdir -p "$dir"
  cc -std=c11 "${SO_FLAGS[@]}" -DFAKE_LEGACY "$@" \
    -o "$dir/libmtk_litert_dispatch_legacy.so" mediatek_dispatch_compat_test.c
  cc -std=c11 "${SO_FLAGS[@]}" -o "$dir/libLiteRtDispatch_MediaTek.so" "$src" \
    ${LIBS[@]+"${LIBS[@]}"}
}

build_case "$D/full" mediatek_dispatch_compat.c
build_case "$D/minimal" mediatek_dispatch_compat.c -DFAKE_NO_OPTIONAL
mkdir -p "$D/missing"
cc -std=c11 "${SO_FLAGS[@]}" -o "$D/missing/libLiteRtDispatch_MediaTek.so" \
  mediatek_dispatch_compat.c ${LIBS[@]+"${LIBS[@]}"}

shifted="$D/shifted.c"
sed 's/memcpy(g_basic\.f, g_legacy\.interface, sizeof(g_basic\.f));/memcpy(g_basic.f, g_legacy.interface + 1, sizeof(g_basic.f) - sizeof(Fn));/' \
  mediatek_dispatch_compat.c > "$shifted"
if cmp -s mediatek_dispatch_compat.c "$shifted"; then
  echo "FAIL: the shifted-table mutation did not apply (the copy line changed)"
  exit 1
fi
build_case "$D/shifted" "$shifted"

runners=(plain)
cc -std=c11 -Wall -Wextra -Werror -o "$D/runner_plain" \
  mediatek_dispatch_compat_test.c ${LIBS[@]+"${LIBS[@]}"}
if [ -n "${LITERT_DIR:-}" ]; then
  # build_config.h is generated by CMake/Bazel; the dispatch header only needs
  # it to exist.
  mkdir -p "$D/gen/litert/build_common"
  sed -E 's/#cmakedefine01 ([A-Z_]+)/#define \1 0/; s/#cmakedefine ([A-Z_]+).*/\/\* \1 \*\//; s/@[A-Za-z_]+@/0/g' \
    "$LITERT_DIR/litert/build_common/build_config.h.in" \
    > "$D/gen/litert/build_common/build_config.h"
  cc -std=c11 -Wall -Wextra -DWITH_LITERT_HEADERS -I"$D/gen" -I"$LITERT_DIR" \
    -o "$D/runner_litert" mediatek_dispatch_compat_test.c ${LIBS[@]+"${LIBS[@]}"}
  runners+=(litert)
fi

fail=0
for r in "${runners[@]}"; do
  "$D/runner_$r" "$D/full/libLiteRtDispatch_MediaTek.so" full || {
    echo "FAIL [$r] full"; fail=1; }
  "$D/runner_$r" "$D/minimal/libLiteRtDispatch_MediaTek.so" minimal || {
    echo "FAIL [$r] minimal"; fail=1; }
  if "$D/runner_$r" "$D/missing/libLiteRtDispatch_MediaTek.so" full \
      >/dev/null 2>&1; then
    echo "FAIL [$r] an adapter without the legacy library negotiated"; fail=1
  fi
  # A crash (a NULL slot called) counts as the expected failure too.
  if "$D/runner_$r" "$D/shifted/libLiteRtDispatch_MediaTek.so" full \
      >/dev/null 2>&1; then
    echo "FAIL [$r] the shifted-table adapter passed: the test cannot see it"
    fail=1
  else
    echo "PASS [$r] shifted table detected"
  fi
done
exit $fail
