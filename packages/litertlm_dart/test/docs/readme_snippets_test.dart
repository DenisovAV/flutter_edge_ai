// Every ```dart block of the README (the pub.dev page) compiles against this
// package.
//
// Each block becomes the body of its own async function in one generated
// file, with the imports written in any block of that document hoisted to the
// top, and `dart analyze` runs over it: an error or a warning fails the test.
// A block may use the inputs in [_placeholders] without declaring them; they
// are data a real program would already have, never an API name, so a renamed
// or removed API fails here instead of in a reader's program.
@TestOn('vm')
library;

import 'dart:io';

import 'package:test/test.dart';

/// The documents whose blocks are compiled, relative to the package.
const _documents = ['README.md'];

const _preamble = '''
// GENERATED by test/docs/readme_snippets_test.dart, deleted after each run.
// ignore_for_file: type=lint, unused_import, unused_local_variable, unused_element, dead_code, unused_catch_clause, dead_code_on_catch_subtype
import 'dart:typed_data';
''';

/// Inputs a block may use without declaring them: data and objects a real
/// program already has. Never an API name.
const _placeholders = '''
late String modelPath;
late String embeddingModelPath;
late String cacheDir;
late String imagePath;
late Uint8List imageBytes;
late Uint8List audioBytes;
''';

/// The ```dart blocks of [markdown]: each as its first line number and its
/// lines.
List<(int, List<String>)> dartBlocks(List<String> markdown) {
  final blocks = <(int, List<String>)>[];
  List<String>? current;
  var start = 0;
  var inFence = false;
  for (var i = 0; i < markdown.length; i++) {
    final fence = RegExp(r'^```(\w*)\s*$').firstMatch(markdown[i]);
    if (fence != null) {
      if (!inFence) {
        inFence = true;
        start = i + 2;
        current = fence.group(1) == 'dart' ? <String>[] : null;
      } else {
        inFence = false;
        if (current != null) blocks.add((start, current));
        current = null;
      }
      continue;
    }
    current?.add(markdown[i]);
  }
  return blocks;
}

void main() {
  for (final document in _documents) {
    final file = File(document);
    test('every dart block of $document compiles', () async {
      final blocks = dartBlocks(file.readAsLinesSync());
      // A document whose blocks all went missing is not a pass.
      expect(blocks, isNotEmpty, reason: '$document has no dart blocks');

      final imports = <String>{};
      final body = StringBuffer();
      for (final (index, (line, lines)) in blocks.indexed) {
        body.writeln('// $document:$line');
        body.writeln('Future<void> snippet$index() async {');
        for (final l in lines) {
          if (l.startsWith('import ')) {
            imports.add(l);
          } else {
            body.writeln(l);
          }
        }
        body.writeln('}');
      }
      final source = '$_preamble${imports.join('\n')}\n\n$_placeholders\n$body';
      final generated = File('test/docs/_snippets_$pid.dart')
        ..writeAsStringSync(source);
      addTearDown(() {
        if (generated.existsSync()) generated.deleteSync();
      });

      final result = await Process.run(Platform.resolvedExecutable, [
        'analyze',
        '--no-fatal-warnings',
        generated.path,
      ]);
      final out = '${result.stdout}${result.stderr}';
      final problems = out
          .split('\n')
          .where((l) => RegExp(r'^\s*(error|warning) -').hasMatch(l))
          .toList();
      expect(
        problems,
        isEmpty,
        reason:
            '${problems.join('\n')}\n\nGenerated from $document:\n'
            '${_numbered(source)}',
      );
    }, skip: file.existsSync() ? false : '$document is not here');
  }
}

String _numbered(String source) => [
  for (final (i, l) in source.split('\n').indexed) '${i + 1}: $l',
].join('\n');
