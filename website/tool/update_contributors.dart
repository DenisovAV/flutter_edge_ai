// Regenerates lib/contributors/contributors_data.g.dart: everyone GitHub
// counts as a contributor to the repository, minus the maintainers listed in
// lib/contributors/maintainers.dart and minus bots. Logins and avatar ids
// only — the page shows nothing about them that GitHub does not show next to
// their commits.
//
// Run from website/ by hand, e.g. at a release:
//
//   dart run tool/update_contributors.dart
//
// The site build never calls GitHub, so a deploy does not depend on its rate
// limits. One request per 100 contributors; GITHUB_TOKEN is used when set.

import 'dart:convert';
import 'dart:io';

import 'package:fluttergemma_website/contributors/maintainers.dart';

const _repo = 'DenisovAV/flutter_edge_ai';
const _output = 'lib/contributors/contributors_data.g.dart';

/// GitHub logins are letters, digits and hyphens, so one can sit in a Dart
/// string literal as it is; anything else is refused rather than escaped.
final _login = RegExp(r'^[A-Za-z0-9-]+$');

Future<void> main() async {
  final client = HttpClient();
  try {
    final token = Platform.environment['GITHUB_TOKEN'];
    final skip = {for (final m in maintainers) m.login.toLowerCase()};

    final people = <({String login, int id, int commits})>[];
    for (var page = 1; ; page++) {
      final batch =
          await _get(
                client,
                token,
                '/repos/$_repo/contributors?per_page=100&page=$page',
              )
              as List<Object?>;
      if (batch.isEmpty) break;
      for (final entry in batch.cast<Map<String, Object?>>()) {
        final login = entry['login']! as String;
        if (entry['type'] != 'User' || login.endsWith('[bot]')) continue;
        if (skip.contains(login.toLowerCase())) continue;
        if (!_login.hasMatch(login)) {
          throw FormatException('Not a GitHub login', login);
        }
        people.add((
          login: login,
          id: entry['id']! as int,
          commits: entry['contributions']! as int,
        ));
      }
    }
    people.sort((a, b) {
      final byCommits = b.commits.compareTo(a.commits);
      return byCommits != 0 ? byCommits : a.login.toLowerCase().compareTo(b.login.toLowerCase());
    });

    final out = StringBuffer()
      ..writeln(
        '// GENERATED by tool/update_contributors.dart - do not edit by hand.',
      )
      ..writeln(
        '// Contributors to $_repo other than the maintainers, most commits first.',
      )
      ..writeln()
      ..writeln("import 'contributor.dart';")
      ..writeln()
      ..writeln('const contributors = <Contributor>[');
    for (final p in people) {
      out.writeln("  Contributor(login: '${p.login}', githubId: ${p.id}),");
    }
    out.writeln('];');
    File(_output).writeAsStringSync(out.toString());
    await Process.run('dart', ['format', _output]);
    stdout.writeln('Wrote ${people.length} contributors to $_output.');
  } finally {
    client.close();
  }
}

Future<Object?> _get(HttpClient client, String? token, String path) async {
  final request = await client.getUrl(Uri.parse('https://api.github.com$path'));
  request.headers
    ..set(HttpHeaders.acceptHeader, 'application/vnd.github+json')
    ..set(HttpHeaders.userAgentHeader, 'flutteredge.ai contributors page');
  if (token != null && token.isNotEmpty) {
    request.headers.set(HttpHeaders.authorizationHeader, 'Bearer $token');
  }
  final response = await request.close();
  final body = await response.transform(utf8.decoder).join();
  if (response.statusCode != 200) {
    throw HttpException('GET $path: ${response.statusCode} $body');
  }
  return jsonDecode(body);
}
